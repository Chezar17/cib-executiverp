-- 1) Cases (one row = one card on the board)
CREATE TABLE IF NOT EXISTS public.cb_cases (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  case_no               bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  title                 text NOT NULL,
  description           text NOT NULL DEFAULT '',
  status                text NOT NULL DEFAULT 'todo'
                        CHECK (status IN ('todo','in_progress','in_review','blocker','completed')),
  priority              text NOT NULL DEFAULT 'medium'
                        CHECK (priority IN ('low','medium','high','critical')),
  division              text NOT NULL DEFAULT 'CID'
                        CHECK (division IN ('CID','GRD','JOINT')),
  tags                  text[] NOT NULL DEFAULT '{}',
  assignees             text[] NOT NULL DEFAULT '{}',      -- detective badges
  checklist             jsonb  NOT NULL DEFAULT '[]'::jsonb, -- [{ id, text, done }]
  start_date            date,
  due_date              date,
  linked_report_id      text,                              -- investigation_reports.id
  linked_report_number  text,                              -- e.g. CID-022 (for display)
  sort_order            double precision NOT NULL DEFAULT 0,
  comment_count         integer NOT NULL DEFAULT 0,
  created_by            text,
  created_by_name       text,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_by            text,
  updated_at            timestamptz NOT NULL DEFAULT now(),
  completed_at          timestamptz,
  is_deleted            boolean NOT NULL DEFAULT false,
  CONSTRAINT cb_cases_checklist_is_array CHECK (jsonb_typeof(checklist) = 'array')
);

CREATE INDEX IF NOT EXISTS cb_cases_board_idx
  ON public.cb_cases (is_deleted, status, sort_order);

-- 2) Comments + activity log (right-hand panel of a case)
CREATE TABLE IF NOT EXISTS public.cb_case_activity (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  case_id      uuid NOT NULL REFERENCES public.cb_cases(id) ON DELETE CASCADE,
  kind         text NOT NULL CHECK (kind IN ('comment','event')),
  actor_badge  text,
  actor_name   text,
  body         text NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  is_deleted   boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS cb_case_activity_case_idx
  ON public.cb_case_activity (case_id, created_at);

-- 3) Lock the tables so only the website's server can read/write them.
--    The server uses SUPABASE_SERVICE_ROLE_KEY (already needed by Nexus Mail).
ALTER TABLE public.cb_cases          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cb_case_activity  ENABLE ROW LEVEL SECURITY;
